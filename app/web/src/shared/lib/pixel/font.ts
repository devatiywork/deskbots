const FONT_W: Record<string, number> = { 'Ж': 5, 'И': 5, 'Й': 5, 'Ш': 5, 'Щ': 5, 'Ы': 5, 'Ю': 5, 'Ъ': 4 };
// значки над буквой в мелких пикселях при клетке 2
const FONT_MARK: Record<string, [number, number][]> = { 'Й': [[3, -3], [6, -3], [4, -2], [5, -2]], 'Ё': [[1, -2], [4, -2]] };

const glyphW = (ch: string) => FONT_W[ch] || 3;

/** Ширина строки в клетках шрифта. */
export const textW = (s: string | number) => [...String(s).toUpperCase()].reduce((w, ch) => w + glyphW(ch) + 1, 0) - 1;

/** Текст в мелких пикселях: px — размер клетки шрифта, hi — светлая верхняя кромка у каждой клетки (как у неоновой трубки). */
export function textQ(s: string | number, x: number, y: number, px: number, col: string, hi?: string | null) {
  let cx = 0;
  for (const ch of String(s).toUpperCase()) {
    const f = FONT[ch] || FONT['-'], w = glyphW(ch);
    for (let p = 0; p < f.length; p++) if (f[p] === '1') {
      const gx = x + (cx + (p % w)) * px, gy = y + ((p / w) | 0) * px;
      Q(gx, gy, px, px, col);
      if (hi) Q(gx, gy, px, 1, hi);
    }
    for (const [mx, my] of FONT_MARK[ch] || []) Q(x + cx * px + Math.round((mx * px) / 2), y + (px < 2 ? -2 : my), 1, 1, col);
    cx += w + 1;
  }
}
